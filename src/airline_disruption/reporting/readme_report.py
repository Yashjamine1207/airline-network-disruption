def _explain_and_errors(inp: Inputs, ev: Evidence) -> str:
    capacity = inp.csv(inp.final_name(SEVERE, "capacity"), required=True)
    day1, day10 = _day_row(capacity, "1%"), _day_row(capacity, "10%")
    lines = []
    importance, families = inp.csv(inp.shap_name("global")), inp.csv(inp.shap_name("family"))
    if importance is not None and families is not None and len(importance) >= 3 and len(families):
        top = ", ".join(f"{r.feature} ({pct(r.share_of_total, 0)})" for r in importance.head(3).itertuples())
        lead = families.sort_values("share_of_total", ascending=False).iloc[0]
        lines.append(f"SHAP on 2022 data: the features that moved the model most were {top}. The biggest feature group was {lead['family']}, at {pct(lead['share_of_total'], 0)} of the total.")
    lines.append("SHAP shows what the model used. It does not show what caused a delay.")
    lines.append(f"Inside each day, the top 10% list leaves {whole(day10['events_missed'])} severe delays outside it and holds {whole(day10['false_alerts'])} flights that were not severely delayed.")
    lines.append(f"The top 1% list catches {whole(day1['events_captured'])} severe delays and holds {whole(day1['false_alerts'])} false alerts.")
    lines.append("A single score hides a lot. The error analysis report breaks the results down by period, carrier, airport, hour, delay size and missing data.")
    return "\n".join(["## Explainability and error analysis", "", bullets(lines)])


def _results(inp: Inputs, ev: Evidence) -> str:
    summary = inp.csv(inp.final_name(SEVERE, "summary"), required=True)
    calibration = inp.csv(inp.final_name(SEVERE, "calibration"), required=True)
    fin = summary[summary["period"] == "final_2023"].copy()
    fin["interval_text"] = [interval(l, h) for l, h in zip(fin["pr_auc_low"], fin["pr_auc_high"])]
    fin["scorer_name"] = [plain_scorer(s) if s.startswith("baseline_") else "LightGBM (locked model)" for s in fin["scorer"]]
    locked = calibration[calibration["variant"].str.contains("locked primary")]
    r22, r23 = facts.one(locked, period="validation_2022"), facts.one(locked, period="final_2023")
    prev22 = facts.one(summary, period="validation_2022", scorer="lightgbm_locked")["prevalence"]
    prev23 = facts.one(summary, period="final_2023", scorer="lightgbm_locked")["prevalence"]
    line = (f"Calibration: the ratio of predicted to observed severe delays was {num(r22['predicted_to_observed'], 3)} on 2022 and {num(r23['predicted_to_observed'], 3)} on 2023. "
            "A ratio of 1 is perfect.")
    if r23["predicted_to_observed"] < r22["predicted_to_observed"] and prev23 > prev22:
        line += (f" The severe-delay rate rose from {pct(prev22, 2)} to {pct(prev23, 2)}, so the probabilities were too low in 2023. "
                 "A fixed probability cutoff is not stable when the event rate moves.")
    parts = ["## Results in more detail", "", "**Severe arrival delay (120 minutes or more), 2023 final test, scored once.**", "",
             md_table(fin, [("Scorer", "scorer_name", None), ("PR-AUC", "pr_auc", num), ("95% interval", "interval_text", None), ("Lift", "lift", lambda v: num(v, 2)),
                            ("ROC-AUC", "roc_auc", lambda v: num(v, 3))]), "", line, "",
             "**Regression, recovery and network.** Arrival-delay regression models were checked on validation data only. No regression model was locked, so none was scored on 2023. "
             "Airport recovery, network and association results are in the reports listed below."]
    return "\n".join(parts)


# ============================================================================================ repository, reports, reproduction
def _layout(inp: Inputs) -> str:
    # reports/evaluation/ is written by the same run, so it counts as present even on a fresh checkout.
    present = [(path, why) for path, why in LAYOUT if path == "reports/evaluation/" or _exists(inp, path)]
    present.append(("data/", "Raw and processed data. Not in Git"))
    width = max(len(path) for path, _ in present)
    tree = [f"{REPO_NAME}/"]
    for i, (path, why) in enumerate(present):
        branch = "\u2514\u2500\u2500 " if i == len(present) - 1 else "\u251c\u2500\u2500 "
        tree.append(f"{branch}{path.ljust(width)}  # {why}")
    return "\n".join(["## Repository structure", "", "```text", *tree, "```"])


def _reports(inp: Inputs) -> str:
    found = [(name, why) for name, why in REPORTS if name in BUILT_HERE or _exists(inp, f"reports/evaluation/{name}")]
    return "\n".join(["## Key reports", "", bullets([f"[`reports/evaluation/{name}`](reports/evaluation/{name}): {why}" for name, why in found])])


def _figures(inp: Inputs) -> str:
    shown = [(name, alt) for name, alt in FIGURES if _exists(inp, f"reports/figures/{name}")]
