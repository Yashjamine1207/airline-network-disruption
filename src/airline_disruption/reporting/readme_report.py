PLAIN_SCORERS = {
    "baseline_prevalence": "overall rate", "baseline_carrier_rate": "carrier history", "baseline_origin_rate": "origin airport history",
    "baseline_destination_rate": "destination airport history", "baseline_route_rate": "route history",
}
PLAIN_CLAIMS = {
    "C1_skill_over_chance": "ranks better than chance",
    "C2_beats_history": "beats the strongest history rule",
    "C3_ranking_not_only_seasonal": "still works when flights are ranked inside each day",
}
PLAIN_METHODS = {"uncalibrated": "no calibration", "platt": "Platt scaling", "isotonic": "isotonic regression"}
METHOD_GLOSS = {"platt": "Platt scaling (a sigmoid curve)", "isotonic": "isotonic regression (a step-shaped curve)", "uncalibrated": "no calibration"}

GLOSSARY = (
    "**Severe delay**: the flight lands 120 minutes or more after its planned arrival time. This line is a project choice, not an official rule.",
    "**Prediction time**: 2 hours before the planned departure. The model may use only what is known by then.",
    "**Leakage**: using information that was not known at prediction time. It makes results look better than they are.",
    "**Date-based split**: train on earlier dates and test on later dates, as in real use. Flights are never shuffled across time.",
    "**Baseline**: a simple rule, such as a carrier's past delay rate. A model must beat it to be worth using.",
    "**PR-AUC**: a score from 0 to 1 for how well a model puts rare events at the top of a ranked list. Random ranking scores about the event rate.",
    "**Lift**: PR-AUC divided by the event rate. A lift of 1 means no better than chance.",
    "**Precision and recall**: precision is the share of flagged flights that were really delayed. Recall is the share of all delayed flights that were flagged.",
    "**Calibration**: whether a predicted 5% chance really happens about 5% of the time.",
    "**SHAP**: a method that splits one prediction into the part each feature added. It describes the model, not the real world.",
)


def _exists(inp: Inputs, relative: str) -> bool:
    return (inp.root / relative).exists()


def plain_scorer(name: str) -> str:
    return PLAIN_SCORERS.get(name, name.replace("baseline_", "").replace("_", " "))


def _sentence(text: str) -> str:
    text = text.strip()
    return text if text.endswith((".", "!", "?")) else text + "."


def _day_row(capacity: pd.DataFrame, share: str) -> pd.Series:
    return facts.one(capacity, period="final_2023", scheme="by_day", capacity=share)


# ============================================================================================ opening sections
def _opening(inp: Inputs, ev: Evidence) -> str:
    summary = inp.csv(inp.final_name(SEVERE, "summary"), required=True)
    fin = locked_scorer_row(summary)
    intro = ("This project looks at flights that land two or more hours late, and at flights that are cancelled. It asks one simple question: "
             "two hours before a flight leaves, can its schedule alone tell us which flights are more likely to be badly delayed? "
             f"These flights are rare ({pct(fin['prevalence'], 2)} of the 2023 flights in this data), so the question is hard. "
             "The project also studies how airports and routes behave when disruption builds up and when it clears, and how far the predicted probabilities can be trusted.")
    scope = f"> **Scope:** {POSITIONING} It has no API, no deployment, no streaming and no live airline data."
    return "\n\n".join([intro, scope])


def _plain_words(inp: Inputs, ev: Evidence) -> str:
    summary = inp.csv(inp.final_name(SEVERE, "summary"), required=True)
    capacity = inp.csv(inp.final_name(SEVERE, "capacity"), required=True)
    d = ev.target(SEVERE)
    failed = failed_claims(d["claims"])
    fin = locked_scorer_row(summary)
    day10 = _day_row(capacity, "10%")
    p = ev.lock["periods"]
    if not failed:
        result = (f"The model ranks severe delays better than chance and better than the strongest simple rule. Its PR-AUC is {num(fin['pr_auc'])}, "
                  f"which is {num(fin['lift'], 2)} times what a random ranking would score.")
    else:
        names = ", ".join(PLAIN_CLAIMS.get(name, name) for name in failed)
        result = (f"The model passed {3 - len(failed)} of 3 checks that were fixed in advance. It did not pass: {names}. "
                  f"Its PR-AUC is {num(fin['pr_auc'])}, which is {num(fin['lift'], 2)} times what a random ranking would score.")
    if day10["recall"] < 0.5:
        result += f" Even so, most severe delays ({pct(1 - day10['recall'], 0)}) are not in its top 10% of flights each day."
    lines = [
        f"A flight counts as **severely delayed** here if it lands 120 minutes (2 hours) or more after its planned arrival time. This line is our own choice, not an official rule. "
        f"In the 2023 test data, {pct(fin['prevalence'], 2)} of flights were severely delayed.",
        "The model sees only what is known **two hours before departure**: the planned time, the airline, the two airports and the route. It never sees what happens on the day.",
        f"We trained on flights from {p['fit']}, stopped training early using {p['early_stop']}, chose between models on {p['validation']}, "
        f"locked every choice in a sealed file, and then scored {p['final_test']} once.",
        result,
    ]
    lines.append("Cancellations: no model was selected. The baseline showed no skill over chance and did not beat the strongest history rule."
                 if not cancel_outcome_positive(ev.target(CANCEL)["claims"])
                 else "Cancellations: the plain baseline passed at least one of the first two checks. It stays a ranking-only baseline.")
    rejected = list(ev.lock.get("rejected_challengers", {}))
    if rejected:
        lines.append(f"{len(rejected)} neural-network models were tested and rejected. The simpler LightGBM model is the result, and that is a valid outcome.")
    return "\n".join(["## The project in plain words", "", bullets(lines)])


def _outcome(inp: Inputs, ev: Evidence) -> str:
    summary = inp.csv(inp.final_name(SEVERE, "summary"), required=True)
    capacity = inp.csv(inp.final_name(SEVERE, "capacity"), required=True)
    d = ev.target(SEVERE)
    fin = locked_scorer_row(summary)
    c2 = d["claims"]["C2_beats_history"]
    base = facts.one(summary, period="final_2023", scorer=c2["baseline"])
    n_features = ev.locked(SEVERE).get("n_features")
    model = "LightGBM" + (f" with {n_features} schedule, carrier, airport and route features" if n_features else "") + ", locked before 2023 was read"
    rows = [
        ("Model", model),
        ("Final test period", ev.lock["periods"]["final_test"]),
        ("Flights scored", whole(fin["rows"])),
        ("Severely delayed flights", whole(fin["events"])),
        ("Share of flights severely delayed", pct(fin["prevalence"], 2)),
        ("PR-AUC of the model", f"{num(fin['pr_auc'])} {interval(fin['pr_auc_low'], fin['pr_auc_high'])}"),
        (f"PR-AUC of the strongest simple rule ({plain_scorer(c2['baseline'])})", num(base["pr_auc"])),
        ("Lift over chance", num(fin["lift"], 2)),
    ]
    table = md_table(pd.DataFrame(rows, columns=["measure", "result"]), [("Final test measure", "measure", None), ("Result", "result", None)])
    part = _order(capacity[(capacity["period"] == "final_2023") & (capacity["scheme"] == "by_day")], "capacity", CAPACITY_ORDER)
    review = md_table(part, [
        ("Share of each day's flights reviewed", "capacity", None), ("Flights reviewed", "reviewed", whole), ("Severe delays caught", "events_captured", whole),
        ("Share of all severe delays caught", "recall", pct), ("Reviewed flights that were severely delayed", "precision", pct), ("False alerts", "false_alerts", whole),
    ])
    return "\n".join(["## Project outcome", "", "The numbers below come from the 2023 final test. The model was scored on these flights once.", "", table, "",
                      "**What-if review lists.** Each day, flights are ranked by predicted risk and the top share is flagged for review. "
                      "A false alert is a flagged flight that was not severely delayed.", "", review, "",
                      "The review lists are a what-if on past data. They show how well the ranking works. They are not airline decisions, costs or savings."])


